import math
from vpuc import Diagram
d = Diagram("Figure 4 — Use Case Diagram: Admin")
DX, DY = -170, 640
def at(r, deg): a = math.radians(deg); return DX + r*math.cos(a), DY + r*math.sin(a)
RI, RO = 640, 920
def U(r, deg, *a, **k): x, y = at(r, deg); return d.uc(x, y, *a, **k)
d.boundary(140, 105, 880, 1210, "PowerMe Platform")
a1 = U(RI, -48, "UC-ADM-01", "Manage User Accounts")
a2 = U(RI, -38, "UC-ADM-02", "Assign Roles and Permissions")
a3 = U(RI, -28, "UC-ADM-03", "Manage Charge Point Registry")
a4 = U(RI, -18, "UC-ADM-04", "Manage RFID Cards")
a5 = U(RI, -8, "UC-ADM-05", "Configure Free-Vend Tag")
a8 = U(RO, 0, "UC-ADM-08", "Handle Billing Exceptions")
a7 = U(RI, 10, "UC-ADM-07", "Monitor Charge Point Network")
a10 = U(RI, 32, "UC-ADM-10", "View Transactions & Revenue")
a6 = U(RI, 43, "UC-ADM-06", "Manage Policy Templates", tag="Should")
login = d.uc(330, 1225, "UC-ACC-04", "Log In", ep=["log out"])
logout = d.uc(a8["x"], 1225, "UC-ACC-05", "Log Out")
AD = d.actor(DX, DY, "Admin")
US = d.actor(DX, 1225, "User")
PG = d.actor(1150, a8["y"]-90, "Payment Gateway", "system")
EIP = d.actor(1150, a8["y"]+90, "E-Invoice Provider", "system")
for u in [a1, a2, a3, a4, a5, a8, a7, a10, a6]: d.assoc(AD, u)
d.assoc(US, login); d.gen(AD, US)
d.assoc(PG, a8); d.assoc(EIP, a8)
d.dep(logout, login, "Extend", ly=-8)
d.save("ucd-admin.svg")
