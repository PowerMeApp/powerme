import math
from vpuc import Diagram
d = Diagram("Figure 3 — Use Case Diagram: Driver")
DX, DY = -170, 640
def at(r, deg): a = math.radians(deg); return DX + r*math.cos(a), DY + r*math.sin(a)
RI, RO = 680, 1200
def U(r, deg, *a, **k): x, y = at(r, deg); return d.uc(x, y, *a, **k)
d.boundary(130, 50, 1100, 1270, "PowerMe Platform")
acc1 = U(RI, -51, "UC-ACC-01", "Register Account")
acc2 = U(RI, -42, "UC-ACC-02", "Manage Driver Profile")
acc3 = U(RI, -33.5, "UC-ACC-03", "Manage Vehicle Profile")
chg1 = U(RI, -23, "UC-CHG-01", "Find Charging Station", ep=["station suggestion"])
chg8 = U(RI, -11.5, "UC-CHG-08", "Get Availability Alert", tag="Could")
chg6 = U(RO, -6, "UC-CHG-06", "Reserve Charging Connector", tag="Should")
chg3 = U(RO, 0, "UC-CHG-03", "Stop Charging Session")
chg2 = U(RO, 6, "UC-CHG-02", "Start Charging Session", ep=["insufficient credit"])
pay1 = U(RO, 13, "UC-PAY-01", "Top Up Charging Credit", ep=["redeem points"])
chg4 = U(RI, 18, "UC-CHG-04", "Monitor Charging Progress")
chg5 = U(RI, 26.5, "UC-CHG-05", "Report Faulty Charge Point")
pay2 = U(RI, 35, "UC-PAY-02", "View Charging History")
pay4 = U(RI, 43.5, "UC-PAY-04", "View Loyalty Points")
chg7 = d.uc(chg6["x"], chg1["y"]-10, "UC-CHG-07", "Get Station Suggestion")
pay3 = d.uc(pay1["x"], pay1["y"]+150, "UC-PAY-03", "Redeem Loyalty Points")
login = d.uc(340, 1235, "UC-ACC-04", "Log In", ep=["log out"])
logout = d.uc(pay1["x"], 1235, "UC-ACC-05", "Log Out")
DR = d.actor(DX, DY, "Driver")
US = d.actor(DX, 1235, "User")
MAP = d.actor(1330, chg7["y"], "Map & Routing Service", "system")
CP = d.actor(1330, chg3["y"], "Charge Point", "system")
PG = d.actor(1330, pay1["y"]-40, "Payment Gateway", "system")
EIP = d.actor(1330, pay1["y"]+120, "E-Invoice Provider", "system")
for u in [acc1, acc2, acc3, chg1, chg8, chg6, chg3, chg2, pay1, chg4, chg5, pay2, pay4]:
    d.assoc(DR, u)
d.assoc(US, login); d.gen(DR, US)
for u in [chg6, chg3, chg2]: d.assoc(CP, u)
d.assoc(MAP, chg7)
for a in [PG, EIP]: d.assoc(a, pay1)
d.dep(chg7, chg1, "Extend", ly=-8)
d.dep(pay1, chg2, "Extend", lx=48)
d.dep(pay3, pay1, "Extend", lx=48)
d.dep(logout, login, "Extend", ly=-8)
d.save("ucd-driver.svg")
